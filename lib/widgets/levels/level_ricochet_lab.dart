  static const List<List<int>> _deltas = [
    [-1, 0], // N
    [0, 1], // E
    [1, 0], // S
    [0, -1], // W
  ];
  static const List<int> _dirBits = [1, 2, 4, 8];

  late _RicochetBoard _board;
  late List<List<int>> _walls;
  late List<int> _robots; // cell index per robot
  int _stageIndex = 0;
  int _stageMoves = 0;
  int _secondsRemaining = _initialBudget.inSeconds;
  Timer? _budgetTimer;
  bool _runFinished = false;

  int _dragRobot = -1;
  Offset _dragDelta = Offset.zero;

  int _totalMoves = 0;
  int _parSolves = 0;
  final List<double> _stageCredits = [];
  final List<List<int>> _history = [];

  @override
  void initState() {
    super.initState();
    widget.registerPartialScoreGetter(_buildPartialOutcome);
    _loadStage(_stageIndex);
    _startBudgetTimer();
  }

  @override
  void dispose() {
    _budgetTimer?.cancel();
    widget.clearPartialScoreGetter();
    super.dispose();
  }

  double get _currentScore {
    final total = _stageCredits.fold<double>(0, (a, b) => a + b);
    return total / _stageCount;
  }

  LevelOutcome _buildPartialOutcome() {
    return LevelOutcome(
      score: _currentScore,
      metrics: {
        'stages_cleared': _stageCredits.length,
        'par_solves': _parSolves,
        'moves': _totalMoves,
      },
    );
  }

  String _formatTime(int seconds) {
    final safe = seconds.clamp(0, 99999);
    final m = (safe ~/ 60).toString().padLeft(2, '0');
    final s = (safe % 60).toString().padLeft(2, '0');
    return '$m:$s';
  }

  void _startBudgetTimer() {
    _budgetTimer?.cancel();
    _budgetTimer = Timer.periodic(const Duration(seconds: 1), (_) {
      if (!mounted || _runFinished) return;
      setState(() {
        if (_secondsRemaining <= 0) return;
        _secondsRemaining--;
        if (_secondsRemaining <= 0) {
          _failRun();
        }
      });
    });
  }

  void _loadStage(int index) {
    _board = _boards[index];
    _walls = List.generate(
      _board.size,
      (r) => List.generate(
        _board.size,
        (c) => int.parse(_board.wallRows[r][c], radix: 16),
      ),
    );
    _robots = List<int>.from(_board.robotCells);
    _stageMoves = 0;
    _history.clear();
  }

  /// Destination cell for sliding [robot] in direction [dir]; may equal the
  /// current cell (illegal move). Must match ricochet_gen.py exactly.
  int _slideDest(int robot, int dir) {
    final size = _board.size;
    var r = _robots[robot] ~/ size;
    var c = _robots[robot] % size;
    final occupied = <int>{
      for (var i = 0; i < _robots.length; i++)
        if (i != robot) _robots[i],
    };
    while (true) {
      if (_walls[r][c] & _dirBits[dir] != 0) break;
      final nr = r + _deltas[dir][0];
      final nc = c + _deltas[dir][1];
      if (occupied.contains(nr * size + nc)) break;
      r = nr;
      c = nc;
    }
    return r * size + c;
  }

  void _slide(int robot, int dir) {
    if (_runFinished) return;
    final dest = _slideDest(robot, dir);
    if (dest == _robots[robot]) return;
    setState(() {
      _history.add(List<int>.from(_robots));
      _robots[robot] = dest;
      _stageMoves++;
      _totalMoves++;
      HapticFeedback.selectionClick();
      if (_robots[_board.targetRobot] == _board.targetCell) {
        if (_stageMoves <= _board.optimalMoves) {
          _onStageCleared(1.0, atPar: true);
        } else {
          HapticFeedback.heavyImpact();
        }
      }
    });
  }

  void _undo() {
    if (_runFinished || _history.isEmpty) return;
    setState(() {
      _robots = _history.removeLast();
      _stageMoves--;
      _totalMoves--;
    });
  }

  void _resetCurrentStage() {
    if (_runFinished) return;
    HapticFeedback.selectionClick();
    setState(() => _loadStage(_stageIndex));
  }

  /// Credit for banking the current over-par position; quadratic falloff so
  /// sloppy solutions are worth little (par 8 in 10 moves -> 0.64).
  double get _bankCredit {
    final ratio = _board.optimalMoves / _stageMoves;
    return (ratio * ratio).clamp(0.0, 1.0);
  }

  bool get _onRing => _robots[_board.targetRobot] == _board.targetCell;

  void _bankStage() {
    if (_runFinished || !_onRing || _stageMoves <= _board.optimalMoves) return;
    _onStageCleared(_bankCredit, atPar: false);
  }

  void _onStageCleared(double credit, {required bool atPar}) {
    _stageCredits.add(credit);
    if (atPar) _parSolves++;
    HapticFeedback.mediumImpact();

    if (_stageIndex >= _stageCount - 1) {
      _finishRun();
      return;
    }
    _secondsRemaining += _bonusPerStage.inSeconds;
    _stageIndex++;
    _loadStage(_stageIndex);
  }

  void _finishRun() {
    if (_runFinished) return;
    _runFinished = true;
    _budgetTimer?.cancel();
    Future.delayed(const Duration(milliseconds: 400), () {
      if (!mounted) return;
      widget.onComplete(
        LevelOutcome(
          score: _currentScore,
          metrics: {
            'stages_cleared': _stageCredits.length,
            'par_solves': _parSolves,
            'moves': _totalMoves,
            'seconds_left': _secondsRemaining,
          },
        ),
      );
    });
  }

  void _failRun() {
    if (_runFinished) return;
    _runFinished = true;
    _budgetTimer?.cancel();
    Future.delayed(const Duration(milliseconds: 300), () {
      if (!mounted) return;
      widget.onComplete(
        LevelOutcome(
          score: _currentScore,
          metrics: {
            'stages_cleared': _stageCredits.length,
            'par_solves': _parSolves,
            'timed_out': true,
            'moves': _totalMoves,
          },
        ),
      );
    });
  }

  void _onPanStart(Offset local, double cellSize) {
    final size = _board.size;
    final c = (local.dx / cellSize).floor().clamp(0, size - 1);
    final r = (local.dy / cellSize).floor().clamp(0, size - 1);
    final cell = r * size + c;
    _dragRobot = _robots.indexOf(cell);
    _dragDelta = Offset.zero;
  }

  void _onPanEnd() {
    if (_dragRobot == -1) return;
    final d = _dragDelta;
    _dragDelta = Offset.zero;
    if (d.distance < 20) {
      _dragRobot = -1;
      return;
    }
    final int dir;
    if (d.dx.abs() >= d.dy.abs()) {
      dir = d.dx > 0 ? 1 : 3;
    } else {
      dir = d.dy > 0 ? 2 : 0;
    }
    final robot = _dragRobot;
    _dragRobot = -1;
    _slide(robot, dir);
  }

