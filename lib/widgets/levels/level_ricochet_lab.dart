class _BoardPainter extends CustomPainter {
  final int size;
  final List<List<int>> walls;
  final int targetCell;
  final Color targetColor;

  _BoardPainter({
    required this.size,
    required this.walls,
    required this.targetCell,
    required this.targetColor,
  });

  @override
  void paint(Canvas canvas, Size canvasSize) {
    final cell = canvasSize.width / size;

    final floorPaint = Paint()
      ..color = NunuColors.backgroundPaper.withValues(alpha: 0.72);
    canvas.drawRect(
      Rect.fromLTWH(0, 0, canvasSize.width, canvasSize.height),
      floorPaint,
    );

    final gridPaint = Paint()
      ..color = Colors.white.withValues(alpha: 0.07)
      ..strokeWidth = 1;
    for (var i = 1; i < size; i++) {
      canvas.drawLine(
        Offset(i * cell, 0),
        Offset(i * cell, canvasSize.height),
        gridPaint,
      );
      canvas.drawLine(
        Offset(0, i * cell),
        Offset(canvasSize.width, i * cell),
        gridPaint,
      );
    }

    // target ring
    final tr = targetCell ~/ size;
    final tc = targetCell % size;
    final center = Offset((tc + 0.5) * cell, (tr + 0.5) * cell);
    canvas.drawCircle(
      center,
      cell * 0.34,
      Paint()
        ..color = targetColor.withValues(alpha: 0.9)
        ..style = PaintingStyle.stroke
        ..strokeWidth = 3,
    );
    canvas.drawCircle(
      center,
      cell * 0.34,
      Paint()..color = targetColor.withValues(alpha: 0.15),
    );

    final wallPaint = Paint()
      ..color = NunuColors.primaryLight
      ..strokeWidth = 4
      ..strokeCap = StrokeCap.round;
    for (var r = 0; r < size; r++) {
      for (var c = 0; c < size; c++) {
        final w = walls[r][c];
        final left = c * cell;
        final top = r * cell;
        if (w & 1 != 0) {
          canvas.drawLine(
            Offset(left, top),
            Offset(left + cell, top),
            wallPaint,
          );
        }
        if (w & 2 != 0) {
          canvas.drawLine(
            Offset(left + cell, top),
            Offset(left + cell, top + cell),
            wallPaint,
          );
        }
        if (w & 4 != 0) {
          canvas.drawLine(
            Offset(left, top + cell),
            Offset(left + cell, top + cell),
            wallPaint,
          );
        }
        if (w & 8 != 0) {
          canvas.drawLine(Offset(left, top), Offset(left, top + cell), wallPaint);
        }
      }
    }
  }

  @override
  bool shouldRepaint(_BoardPainter old) =>
      old.walls != walls || old.targetCell != targetCell || old.size != size;
}
