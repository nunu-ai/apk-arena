/// Ricochet-robots campaign: eight hardcoded boards, gated progression,
/// internal budget starting at 15:00 with +3:00 after each solved board.
///
/// Robots slide until they hit a wall edge or another robot — no partial
/// moves. Swipe on a robot to slide it. Reaching the ring at par (the BFS
/// optimum) clears the stage at full value; over par the player may bank
/// the stage for (par/moves)^2 credit, so sloppy lines are worth little.
/// Undo and reset are free.
///
/// Every board was generated and BFS-verified by `ricochet_gen.py` with
/// these exact sliding rules. From stage 3 on the target robot provably
/// cannot reach the ring on its own (solo BFS exhausts), and the verified
/// optimal line contains 1-6 crash-stops — moves that end by ramming
/// another robot in open field. Do not edit a board without re-verifying.
class LevelRicochetLab extends LevelWidget {
  const LevelRicochetLab({super.key, required super.onComplete});

  @override
  State<LevelRicochetLab> createState() => _LevelRicochetLabState();
}

class _RicochetBoard {
