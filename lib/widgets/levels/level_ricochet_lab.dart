  Widget _buildBoard() {
    return LayoutBuilder(
      builder: (context, constraints) {
        final size = _board.size;
        final boardSide =
            (constraints.maxWidth - 16).clamp(0.0, constraints.maxHeight);
        final cellSize = boardSide / size;

        return SizedBox(
          width: boardSide,
          height: boardSide,
          child: GestureDetector(
            onPanStart: (d) => _onPanStart(d.localPosition, cellSize),
            onPanUpdate: (d) => _dragDelta += d.delta,
            onPanEnd: (_) => _onPanEnd(),
            child: Stack(
              children: [
                Positioned.fill(
                  child: CustomPaint(
                    painter: _BoardPainter(
                      size: size,
                      walls: _walls,
                      targetCell: _board.targetCell,
                      targetColor: _robotColors[_board.targetRobot],
                    ),
                  ),
                ),
                for (var i = 0; i < _robots.length; i++)
                  AnimatedPositioned(
                    duration: const Duration(milliseconds: 140),
                    curve: Curves.easeOutCubic,
                    left: (_robots[i] % size) * cellSize + cellSize * 0.14,
                    top: (_robots[i] ~/ size) * cellSize + cellSize * 0.14,
                    width: cellSize * 0.72,
                    height: cellSize * 0.72,
                    child: Container(
                      decoration: BoxDecoration(
                        color: _robotColors[i],
                        shape: BoxShape.circle,
                        border: Border.all(
                          color: i == _board.targetRobot
                              ? Colors.white
                              : Colors.white.withValues(alpha: 0.25),
                          width: i == _board.targetRobot ? 2.5 : 1,
                        ),
                        boxShadow: [
                          BoxShadow(
                            color: _robotColors[i].withValues(
                              alpha: i == _board.targetRobot ? 0.6 : 0.3,
                            ),
                            blurRadius: i == _board.targetRobot ? 8 : 4,
                          ),
                        ],
                      ),
                      child: Icon(
                        Icons.smart_toy,
                        color: Colors.white,
                        size: cellSize * 0.36,
                      ),
                    ),
                  ),
              ],
            ),
          ),
        );
      },
    );
  }

