            Padding(
              padding: const EdgeInsets.only(top: 12),
              child: Text(
                '${spec.name}  ·  lit $_litCount',
                style: TextStyle(
                  color: _litCount == 0
                      ? NunuColors.successMain
                      : NunuColors.warningMain,
                  fontSize: 14,
                  fontWeight: FontWeight.w800,
                ),
              ),
            ),
            Expanded(child: Center(child: _buildGrid())),
            _buildControls(),
            const SizedBox(height: 8),
          ],
        ),
      ),
    );
  }

  Widget _buildControls() {
    return TextButton.icon(
      onPressed: _resetStage,
      icon: const Icon(Icons.refresh, size: 18, color: NunuColors.textSecondary),
      label: const Text(
        'reset board',
        style: TextStyle(
          color: NunuColors.textSecondary,
          fontSize: 13,
          fontWeight: FontWeight.w700,
        ),
      ),
    );
  }

  Widget _buildGrid() {
    return LayoutBuilder(
      builder: (context, constraints) {
        final cellSize = min(
          (constraints.maxWidth - 48) / _size,
          (constraints.maxHeight - 16) / _size,
        );
        return SizedBox(
          width: cellSize * _size + 16,
          height: cellSize * _size + 16,
          child: GridView.builder(
            physics: const NeverScrollableScrollPhysics(),
            padding: const EdgeInsets.all(8),
            gridDelegate: SliverGridDelegateWithFixedCrossAxisCount(
              crossAxisCount: _size,
              mainAxisSpacing: 6,
              crossAxisSpacing: 6,
            ),
            itemCount: _size * _size,
            itemBuilder: (_, i) => _buildCell(i ~/ _size, i % _size, cellSize),
          ),
        );
      },
    );
  }

  /// Color for a given cell state. State 0 is "dark/off"; higher states are
  /// distinct lit colors (used by the 3-color boards).
  Color _stateColor(int s) {
    switch (s) {
      case 1:
        return NunuColors.warningMain; // amber
      case 2:
        return const Color(0xFF22D3EE); // cyan
      default:
        return const Color(0xFF1A1A2E); // off
    }
  }

  Widget _buildCell(int r, int c, double size) {
    if (!_isActive(r, c)) {
      // A hole: render as empty void, not tappable.
      return const SizedBox.shrink();
    }
    final s = _state[r][c];
    final lit = s != 0;
    final color = _stateColor(s);

    return GestureDetector(
      onTap: () => _onTap(r, c),
      child: AnimatedContainer(
        duration: const Duration(milliseconds: 200),
        decoration: BoxDecoration(
          color: color,
          borderRadius: BorderRadius.circular(10),
          border: Border.all(
            color: lit
                ? color.withOpacity(0.7)
                : NunuColors.primaryDark.withOpacity(0.3),
            width: 2,
          ),
          boxShadow: lit
              ? [
                  BoxShadow(
                    color: color.withOpacity(0.6),
                    blurRadius: 16,
                    spreadRadius: 2,
                  ),
                ]
              : null,
        ),
        child: Center(
          child: Icon(
            lit ? Icons.lightbulb : Icons.lightbulb_outline,
            color: lit ? Colors.white : Colors.white.withOpacity(0.2),
            size: size * 0.35,
          ),
        ),
      ),
    );
  }
}
