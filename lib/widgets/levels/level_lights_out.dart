      pattern: _kStar,
      holes: {0, 5, 30, 35},
      scramble: 12,
      seed: 1010,
    ),
  ];

  static const int _stageCount = 10;

  // Active stage geometry / rules.
  late int _size;
  late int _colors;
  late List<List<int>> _pattern;
  late Set<int> _holes;
  late List<List<int>> _state; // per-cell state in [0, colors)

  int _stageIndex = 0;
  int _stagesCleared = 0;
  double _efficiencySum = 0; // sum of per-stage min(1, optimal/moves)

  int _stageMoves = 0;
  int _stageOptimal = 0;
  int _litCount = 0;

  int _totalMoves = 0;
  int _totalOptimal = 0;

  bool _done = false;
  bool _advancing = false;

  @override
  void initState() {
    super.initState();
    widget.registerPartialScoreGetter(_buildOutcome);
    _loadStage(0);
  }

  @override
  void dispose() {
    widget.clearPartialScoreGetter();
    super.dispose();
  }

  LevelOutcome _buildOutcome() {
    final score = (_efficiencySum / _stageCount).clamp(0.0, 1.0);
    return LevelOutcome(
      score: score,
      metrics: {
        'stages_cleared': _stagesCleared,
        'moves': _totalMoves,
        'optimal_moves': _totalOptimal,
      },
    );
  }

  bool _isActive(int r, int c) {
    if (r < 0 || r >= _size || c < 0 || c >= _size) return false;
    return !_holes.contains(r * _size + c);
  }

  int _countLit(List<List<int>> grid) {
    int n = 0;
    for (int r = 0; r < _size; r++) {
      for (int c = 0; c < _size; c++) {
        if (_isActive(r, c) && grid[r][c] != 0) n++;
      }
    }
    return n;
  }

  /// Applies one tap at (r, c) to [grid], cycling the tapped cell and its
  /// pattern-neighbours by +1 (mod colors). Skips holes / out-of-bounds.
  void _applyTap(List<List<int>> grid, int r, int c) {
    for (final d in _pattern) {
      final nr = r + d[0], nc = c + d[1];
      if (_isActive(nr, nc)) {
        grid[nr][nc] = (grid[nr][nc] + 1) % _colors;
      }
    }
  }

  void _loadStage(int index) {
    final spec = _stages[index];
    _size = spec.size;
    _colors = spec.colors;
    _pattern = spec.pattern;
    _holes = spec.holes;

    // Scramble from the solved state until we get a non-trivial, solvable
    // board. Bumping the seed keeps generation deterministic but recoverable.
    List<List<int>> chosen =
        List.generate(_size, (_) => List.filled(_size, 0));
    int optimal = 0;
    for (int attempt = 0; attempt < 64; attempt++) {
      final rng = Random(spec.seed + attempt);
      final grid = List.generate(_size, (_) => List.filled(_size, 0));
      final active = <int>[
        for (int r = 0; r < _size; r++)
          for (int c = 0; c < _size; c++)
            if (_isActive(r, c)) r * _size + c,
      ];
      for (int i = 0; i < spec.scramble; i++) {
        final cell = active[rng.nextInt(active.length)];
        _applyTap(grid, cell ~/ _size, cell % _size);
      }
      if (_countLit(grid) == 0) continue;
      final opt = _optimalMoves(grid);
      if (opt == null || opt == 0) continue;
      chosen = grid;
      optimal = opt;
      break;
    }

    _state = chosen;
    _stageOptimal = optimal;
    _stageMoves = 0;
    _litCount = _countLit(chosen);
  }

  void _onTap(int r, int c) {
    if (_done || _advancing || !_isActive(r, c)) return;
    setState(() {
      _applyTap(_state, r, c);
      _stageMoves++;
      _totalMoves++;
      _litCount = _countLit(_state);
      HapticFeedback.lightImpact();
      if (_litCount == 0) _onStageCleared();
    });
  }

  void _resetStage() {
    if (_done || _advancing) return;
    setState(() {
      _totalMoves -= _stageMoves; // undo this stage's contribution
      _loadStage(_stageIndex);
    });
    HapticFeedback.selectionClick();
  }

  void _onStageCleared() {
    _stagesCleared++;
    _totalOptimal += _stageOptimal;
    final eff = _stageMoves <= 0
        ? 1.0
        : (_stageOptimal / _stageMoves).clamp(0.0, 1.0);
    _efficiencySum += eff;
    HapticFeedback.mediumImpact();

    if (_stageIndex >= _stageCount - 1) {
      _finish();
      return;
    }

    _advancing = true;
    Future.delayed(const Duration(milliseconds: 550), () {
      if (!mounted || _done) return;
      setState(() {
        _stageIndex++;
        _loadStage(_stageIndex);
        _advancing = false;
      });
    });
  }

  void _finish() {
    if (_done) return;
    _done = true;
    HapticFeedback.mediumImpact();
    Future.delayed(const Duration(milliseconds: 600), () {
      if (!mounted) return;
      widget.onComplete(_buildOutcome());
    });
  }

  // ---------------------------------------------------------------------------
  // Solver: minimum number of taps to clear [grid], over GF(colors).
  // Returns null if (unexpectedly) inconsistent.
  // ---------------------------------------------------------------------------

  int? _optimalMoves(List<List<int>> grid) {
    final p = _colors;
    final active = <int>[
      for (int r = 0; r < _size; r++)
        for (int c = 0; c < _size; c++)
          if (_isActive(r, c)) r * _size + c,
    ];
    final n = active.length;
    final varOf = <int, int>{for (int i = 0; i < n; i++) active[i]: i};

    // aug[row][col] = effect on active cell `row` of tapping active cell `col`;
    // last column is the target state to cancel.
    final aug = List.generate(n, (_) => List.filled(n + 1, 0));
    for (int j = 0; j < n; j++) {
      final cell = active[j];
      final jr = cell ~/ _size, jc = cell % _size;
      for (final d in _pattern) {
        final nr = jr + d[0], nc = jc + d[1];
        if (!_isActive(nr, nc)) continue;
        final i = varOf[nr * _size + nc]!;
        aug[i][j] = (aug[i][j] + 1) % p;
      }
    }
    for (int i = 0; i < n; i++) {
      final cell = active[i];
      // Taps *add* to each cell, so to reach 0 we must cancel the current
      // state: solve for an effect of -state (mod p). For p=2 this equals the
      // state itself, but for 3-color boards the negation matters.
      final state = grid[cell ~/ _size][cell % _size] % p;
      aug[i][n] = (p - state) % p;
    }

    final pivotCol = List.filled(n, -1);
    int rank = 0;
    for (int col = 0; col < n && rank < n; col++) {
      int pivotRow = -1;
      for (int row = rank; row < n; row++) {
        if (aug[row][col] != 0) {
          pivotRow = row;
          break;
        }
      }
      if (pivotRow == -1) continue;
      final tmp = aug[rank];
      aug[rank] = aug[pivotRow];
      aug[pivotRow] = tmp;
      final inv = _modInverse(aug[rank][col], p);
      for (int k = col; k <= n; k++) {
        aug[rank][k] = (aug[rank][k] * inv) % p;
      }
      for (int row = 0; row < n; row++) {
        if (row == rank) continue;
        final f = aug[row][col];
        if (f == 0) continue;
        for (int k = col; k <= n; k++) {
          aug[row][k] = (aug[row][k] - f * aug[rank][k]) % p;
          if (aug[row][k] < 0) aug[row][k] += p;
        }
      }
      pivotCol[rank] = col;
      rank++;
    }

    // Consistency check: a zero row with nonzero rhs means no solution.
    for (int row = rank; row < n; row++) {
      if (aug[row][n] != 0) return null;
    }

    final particular = List.filled(n, 0);
    for (int i = 0; i < rank; i++) {
      if (pivotCol[i] != -1) particular[pivotCol[i]] = aug[i][n];
    }

    final pivotSet = {for (int i = 0; i < rank; i++) pivotCol[i]};
    final freeVars = [
      for (int c = 0; c < n; c++)
        if (!pivotSet.contains(c)) c,
    ];

    int weight(List<int> v) => v.fold(0, (a, b) => a + b);

    // No free variables → unique solution.
    if (freeVars.isEmpty) return weight(particular);

    // Null-space basis: one vector per free variable.
    final nullBasis = <List<int>>[];
    for (final fv in freeVars) {
      final v = List.filled(n, 0);
      v[fv] = 1;
      for (int i = 0; i < rank; i++) {
        if (pivotCol[i] != -1 && aug[i][fv] != 0) {
          v[pivotCol[i]] = (p - aug[i][fv]) % p;
        }
      }
      nullBasis.add(v);
    }

    // Search null-space combinations for the lightest solution. Bounded so a
    // pathological board can never hang the UI; falls back to the particular
    // solution if the space is too large to enumerate.
    final nullity = freeVars.length;
    int combos = 1;
    for (int i = 0; i < nullity; i++) {
      combos *= p;
      if (combos > 300000) return weight(particular);
    }

    int best = weight(particular);
    final coeff = List.filled(nullity, 0);
    for (int mask = 1; mask < combos; mask++) {
      // Advance the mixed-radix (base p) counter.
      int carry = 1;
      for (int i = 0; i < nullity && carry > 0; i++) {
        coeff[i] += carry;
        if (coeff[i] >= p) {
          coeff[i] = 0;
        } else {
          carry = 0;
        }
      }
      final candidate = List.of(particular);
      for (int k = 0; k < nullity; k++) {
        final ck = coeff[k];
        if (ck == 0) continue;
        for (int i = 0; i < n; i++) {
          candidate[i] = (candidate[i] + ck * nullBasis[k][i]) % p;
        }
      }
      final w = weight(candidate);
      if (w < best) best = w;
    }
    return best;
  }

  int _modInverse(int a, int p) {
    a %= p;
    for (int x = 1; x < p; x++) {
      if ((a * x) % p == 1) return x;
    }
    return 1; // p is prime here (2 or 3), so this is unreachable for a != 0
  }

